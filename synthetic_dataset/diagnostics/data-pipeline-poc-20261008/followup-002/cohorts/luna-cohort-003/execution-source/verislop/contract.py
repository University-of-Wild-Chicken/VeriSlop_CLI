@dataclass
class Env:
    export: dict[str, Any]
    decls: dict[str, dict[str, Any]] = field(default_factory=dict)
    hashes: dict[str, str] = field(default_factory=dict)
    diagnostics: list[Diagnostic] = field(default_factory=list)

    @classmethod
    def from_export(cls, export: dict[str, Any], pol: dict[str, Any], phase: str) -> "Env":
        env = cls(export)
        imp = export.get("import", {})
        if not imp.get("ok"):
            env.diagnostics.append(Diagnostic("KERNEL_REJECTION", f"{phase}: module could not be imported: {imp.get('error')}"))
            return env
        if imp.get("is_module_system") and imp.get("load_level") != "private":
            env.diagnostics.append(Diagnostic("KERNEL_REJECTION", f"{phase}: module-system acceptance requires the full private declaration environment"))
            return env
        rep = export.get("replay", {})
        if not rep.get("ok"):
            env.diagnostics.append(Diagnostic("KERNEL_REJECTION", f"{phase}: kernel replay rejected the module: {rep.get('error')}"))
            return env
        exported = export.get("constants", [])
        skipped = {name_str(n) for n in rep.get("not_replayed_unsafe_or_partial", [])}
        replayed = {name_str(c["name"]): c for c in exported
                    if c.get("kind") != "missing_after_replay"
                    and "export_error" not in c}
        for c in exported:
            n = name_str(c["name"])
            if "export_error" in c:
                env.diagnostics.append(Diagnostic("UNSUPPORTED_SEMANTICS", f"{phase}: declaration {n} could not be exported: {c['export_error']}"))
                continue
            if c.get("kind") == "missing_after_replay":
                if c.get("replay_exclusion") != "runtime_auxiliary":
                    env.diagnostics.append(Diagnostic("KERNEL_REJECTION", f"{phase}: declaration {n} is missing after kernel replay"))
                else:
                    parent = name_str(c.get("replayed_parent", []))
                    p = replayed.get(parent, {})
                    if (n not in skipped or c.get("omitted_kind") != "definition"
                            or c.get("safety") not in {"unsafe", "partial"}
                            or n != parent + "._unsafe_rec" or p.get("kind") != "definition"
                            or p.get("safety") != "safe"):
                        env.diagnostics.append(Diagnostic("KERNEL_REJECTION", f"{phase}: invalid omitted runtime auxiliary {n}"))
                # Quarantined executable companions are not semantic declarations. A binding,
                # theorem root or definition depending on one cannot gain acceptance here.
                continue
            env.decls[n] = c
            env.hashes[n] = decl_hash(c)
        roots = pol["allowed_import_roots"]
        for m in imp.get("direct_imports", []):
            mod = name_str(m)
            if str(m[0]) not in roots:
                env.diagnostics.append(Diagnostic("UNDECLARED_DEPENDENCY", f"{phase}: import {mod} is outside the allowed toolchain roots {roots}"))
        for n, c in env.decls.items():
            if c["kind"] == "axiom" and pol["forbid_module_axioms"]:
                env.diagnostics.append(Diagnostic("INADMISSIBLE_AXIOM", f"{phase}: the module declares axiom {n}; domain assumptions must be explicit hypotheses"))
        return env

    def axioms(self, n: str) -> list[str]:
        return [name_str(a) for a in self.decls[n].get("axioms", [])]


def binding_names(formalization: dict[str, Any]) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for b in formalization["bindings"]:
        names = ([b["theorem"]] if "theorem" in b else []) + ([b["predicate"]] if "predicate" in b else []) + list(b.get("declarations", []))
        out[b["obligation"]] = names
    for item in formalization["internal_obligations"]:
        out[item["id"]] = [item["theorem"]]
    return out


@dataclass
class Analysis:
    profile: dict[str, Any] | None
    statements: dict[str, dict[str, Any]]
    defeq_requests: list[dict[str, Any]]
    diagnostics: list[Diagnostic]
    registry: list[dict[str, Any]]


def analyze(env: Env, records: list[dict[str, Any]], formalization: dict[str, Any], pol: dict[str, Any],
            toolchain_pin: str, phase: str) -> Analysis:
    diags: list[Diagnostic] = []
    statements: dict[str, dict[str, Any]] = {}
    requests: list[dict[str, Any]] = []
    decls = env.decls
    by_id = {r["id"]: r for r in records}
    bnames = binding_names(formalization)
    kinds = {b["obligation"]: ("theorem" if "theorem" in b else "predicate" if "predicate" in b else "declarations" if "declarations" in b else "none")
             for b in formalization["bindings"]}
    for item in formalization["internal_obligations"]:
        kinds[item["id"]] = "theorem"
    active = [r for r in records if not r["blocked_by"]]

    # -- registry --------------------------------------------------------------------------------
    try:
        registry = decode_registry(decls)
    except RegistryError as exc:
        diags.append(Diagnostic("CLAIM_MUTATION", f"{phase}: obligation registry is missing or malformed: {exc}"))
        return Analysis(None, {}, [], diags, [])
    reg_by_id: dict[str, dict[str, Any]] = {}
    for e in registry:
        if e["id"] in reg_by_id:
            diags.append(Diagnostic("CLAIM_MUTATION", f"{phase}: duplicate registry ID {e['id']}", obligations=[e["id"]]))
        reg_by_id[e["id"]] = e
    for r in active:
        e = reg_by_id.get(r["id"])
        if e is None:
            diags.append(Diagnostic("CLAIM_MUTATION", f"{phase}: registry lacks required obligation {r['id']}", obligations=[r["id"]]))
            continue
        expected = {k: r[k] for k in RECORD_FIELDS}
        got = {k: e[k] for k in RECORD_FIELDS}
        if canonical.dumps(expected) != canonical.dumps(got):
            diags.append(Diagnostic("CLAIM_MUTATION", f"{phase}: registry entry for {r['id']} differs from the frozen claim (revision/kind/role/provenance)", obligations=[r["id"]]))
        if e["bindings"] != bnames.get(r["id"], []):
            diags.append(Diagnostic("CLAIM_MUTATION", f"{phase}: registry bindings for {r['id']} differ from the formalization", obligations=[r["id"]]))
    for oid in reg_by_id:
        if oid not in by_id:
            diags.append(Diagnostic("CLAIM_MUTATION", f"{phase}: registry contains unknown obligation {oid}", obligations=[oid]))

    # -- bindings resolve with the right kinds ---------------------------------------------------------
    for r in active:
        oid, role = r["id"], r["role"]
        kind = kinds.get(oid)
        want = {"guarantee": "theorem", "assumption": "predicate", "declaration": "declarations",
                "exclusion": "none", "open_question": "none"}[role]
        if kind is None:
            diags.append(Diagnostic("STATEMENT_MISMATCH", f"{phase}: no formal binding for {oid}", obligations=[oid]))
            continue
        if kind != want:
            diags.append(Diagnostic("STATEMENT_MISMATCH", f"{phase}: {oid} ({role}) must bind a {want}, not a {kind}", obligations=[oid]))
            continue
        for n in bnames.get(oid, []):
            c = decls.get(n)
            if c is None:
                diags.append(Diagnostic("STATEMENT_MISMATCH", f"{phase}: {oid} binds missing declaration {n}", obligations=[oid]))
            elif kind == "theorem" and c["kind"] != "theorem":
                diags.append(Diagnostic("STATEMENT_MISMATCH", f"{phase}: {oid} binds {n}, which is a {c['kind']}, not a theorem", obligations=[oid]))
            elif kind == "predicate" and c["kind"] != "definition":
                diags.append(Diagnostic("STATEMENT_MISMATCH", f"{phase}: {oid} binds {n}, which is not a definition", obligations=[oid]))
    if any(d.severity == "blocking" for d in diags):
        return Analysis(None, {}, [], diags, registry)

    # -- profile -----------------------------------------------------------------------------------------
    roots: set[str] = set()
    for r in active:
        for n in bnames.get(r["id"], []):
            roots.add(n)
            roots |= constants(decls[n]["type"])
    profile_json, notes = reify.derive_profile(formalization["profile_id"], decls, env.hashes, roots)
    profile = dsl.Profile.from_json(profile_json)
    profile_hash = canonical.digest_json(profile_json)
    pred_owner = {}
    for r in active:
        if r["role"] == "assumption":
            for n in bnames.get(r["id"], []):
                pred_owner[n] = r["id"]
                if n not in {p["lean_decl"] for p in profile.predicates.values()}:
                    diags.append(Diagnostic("UNSUPPORTED_SEMANTICS", f"{phase}: assumption {r['id']} binds {n}, which is not a predicate over DSL sorts", obligations=[r["id"]]))

    # -- per-obligation statements ----------------------------------------------------------------------
    for r in active:
        oid, role = r["id"], r["role"]
        names = bnames.get(oid, [])
        sem_roots = set(names) | {n for x in names for n in constants(decls[x]["type"])}
        clos = closure(sem_roots, decls)
        # A record's full constructor/projection registry is part of its semantic identity,
        # including fields that a particular theorem does not project. Acceptance must freeze
        # those definitions as well as the hashes already recorded in the derived profile.
        record_family = {n for rec in profile.records.values() if rec["lean_decl"] in clos
                         for n in [rec["lean_constructor"], *(f["lean_projection"] for f in rec["fields"])]}
        clos |= closure(record_family, decls)
        for n in clos:
            c = decls[n]
            if c["safety"] != "safe":
                diags.append(Diagnostic("UNSUPPORTED_SEMANTICS", f"{phase}: {oid} depends on {c['safety']} declaration {n}", obligations=[oid]))
            if c["kind"] != "theorem" and "sorryAx" in [name_str(a) for a in c.get("axioms", [])]:
                diags.append(Diagnostic("PROOF_UNRESOLVED", f"{phase}: definition {n} used by {oid} contains `sorry`", obligations=[oid]))
        referenced = {n: env.hashes[n] for n in sorted(clos)}
        st: dict[str, Any] = {
            "id": oid, "revision": r["revision"], "kind": r["kind"], "role": role,
            "bindings": names,
            "semantic_closure": referenced,
            "semantic_closure_hash": canonical.digest_json({"toolchain": toolchain_pin, "declarations": referenced}),
            "hypotheses": [], "unfolded_predicates": [],
        }
        if role == "guarantee":
            thm = names[0]
            ttype = decls[thm]["type"]
            st["lean_symbol"] = thm
            hyps = sorted({pred_owner[p] for p in reify.predicate_constants(ttype, profile) if p in pred_owner})
            formula, why, unfolded = reify.reify_formula(ttype, profile, decls)
            st["unfolded_predicates"] = sorted(unfolded)
            if r["kind"] == "non_vacuity":
                hyps = []
                item = next(i for i in formalization["internal_obligations"] if i["id"] == oid)
                mentioned = constants(ttype)
                for aid in item["witnesses_for"]:
                    preds = bnames.get(aid, [])
                    if by_id.get(aid, {}).get("role") != "assumption":
                        diags.append(Diagnostic("MISSING_WITNESS", f"{phase}: {oid} witnesses {aid}, which is not an assumption", obligations=[oid]))
                    elif not set(preds) & mentioned:
                        diags.append(Diagnostic("MISSING_WITNESS", f"{phase}: witness theorem {thm} does not exercise the frozen predicate of {aid}", obligations=[oid]))
                if formula is None or not dsl.is_existential_shape(formula):
                    diags.append(Diagnostic("MISSING_WITNESS", f"{phase}: non-vacuity theorem {thm} must be a DSL conjunction of existentials ({why})", obligations=[oid]))
            else:
                declared = {d["id"] for d in r["dependencies"] if d["relation"] == "assumes"}
                extra = set(hyps) - declared
                if extra:
                    diags.append(Diagnostic(
                        "STATEMENT_MISMATCH",
                        f"{phase}: theorem {thm} assumes {', '.join(sorted(extra))}, which the interpretation of {oid} does not; "
                        "a formalization must not quietly weaken a guarantee", obligations=[oid]))
            st["hypotheses"] = hyps
            if formula is not None:
                pkg = dsl.make_package(formula, profile.profile_id, encoding=profile.encoding)
                if not dsl.round_trip_ok(pkg, profile):
                    diags.append(Diagnostic("IR_REIFICATION_MISMATCH", f"{phase}: DSL round trip failed for {oid}", obligations=[oid]))
                st.update({
                    "representation": "contract_dsl",
                    "formula_package": pkg,
                    "display": dsl.render(formula),
                    "statement_hash": reify.statement_hash(
                        encoding=profile.encoding, profile_id=profile.profile_id, profile_hash=profile_hash,
                        toolchain=toolchain_pin, payload=formula, referenced=referenced),
                })
                requests.append({"id": oid, "theorem": decls[thm]["name"], "expr": reify.denote_formula(formula, profile)})
            else:
                from .exprjson import canon

                st.update({
                    "representation": "lean_expr",
                    "opaque_reason": why,
                    "statement_hash": reify.statement_hash(
                        encoding=dsl.OPAQUE_ENCODING, profile_id=profile.profile_id, profile_hash=profile_hash,
                        toolchain=toolchain_pin, payload=canon(ttype, []), referenced=referenced),
                })
        else:
            payload = {"registry_entry": f"{REGISTRY_NS}.{oid}", "bindings": {n: env.hashes[n] for n in names}}
            st.update({
                "representation": "typed_metadata",
                "lean_symbol": names[0] if names else f"{REGISTRY_NS}.{oid}",
                "statement_hash": reify.statement_hash(
                    encoding="verislop.typed-metadata/0.1", profile_id=profile.profile_id, profile_hash=profile_hash,
                    toolchain=toolchain_pin, payload=payload, referenced=referenced),
            })
        statements[oid] = st

    # -- witness coverage (strict policy) -----------------------------------------------------------------
    if pol["require_witnesses"]:
        covered = {a for i in formalization["internal_obligations"] for a in i["witnesses_for"]}
        used = {h for st in statements.values() if st["role"] == "guarantee" and by_id[st["id"]]["required"] for h in st["hypotheses"]}
        for aid in sorted(used - covered):
            diags.append(Diagnostic("MISSING_WITNESS", f"{phase}: assumption {aid} is used by required guarantees but no non-vacuity obligation witnesses it", obligations=[aid]))
    for n in notes:
        diags.append(Diagnostic("UNSUPPORTED_SEMANTICS", f"{phase}: {n}", severity="warning"))
    return Analysis(profile_json, statements, requests, diags, registry)


def defeq_diagnostics(response: dict[str, Any], phase: str) -> list[Diagnostic]:
    diags = []
    for item in response.get("defeq", []):
        res = item["result"]
        oid = item["id"]
        if not res.get("ok"):
            diags.append(Diagnostic("IR_REIFICATION_MISMATCH", f"{phase}: denotation check for {oid} failed: {res.get('error')}", obligations=[oid]))
        elif not res.get("typechecks"):
            diags.append(Diagnostic("IR_REIFICATION_MISMATCH", f"{phase}: the DSL denotation of {oid} does not type check", obligations=[oid]))
        elif not res.get("defeq"):
            diags.append(Diagnostic("IR_REIFICATION_MISMATCH", f"{phase}: the DSL denotation of {oid} is not definitionally equal to the theorem", obligations=[oid]))
    return diags


