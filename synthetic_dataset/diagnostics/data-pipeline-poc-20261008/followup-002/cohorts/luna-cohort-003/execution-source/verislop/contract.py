"""Frozen formal challenge: claim records, the Lean obligation registry, statement analysis.

The Lean challenge is the formalizer's candidate source plus a VeriSlop-generated registry
(namespace `VeriSlop.Registry`) of typed metadata binding each obligation's ID, revision, kind,
role, provenance, scope and declaration references to the formal artifact. Registry records are
an index, never evidence: they contain no lifecycle or status field.

`analyze` is shared by the statement checker (formalize), the acceptance service and the
exporter. It works only on the kernel tool's export of a replayed environment.
"""

