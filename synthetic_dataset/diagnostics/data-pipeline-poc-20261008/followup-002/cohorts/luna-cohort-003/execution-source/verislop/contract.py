def lean_string(s: str) -> str:
    out = ['"']
    for ch in s:
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append(f"\\x{ord(ch):02x}")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def _lean_list(items: list[str]) -> str:
    return "[" + ", ".join(items) + "]"


def _guillemet(oid: str) -> str:
    if "»" in oid or "«" in oid:
        raise ValueError(f"obligation ID {oid!r} cannot be a Lean name component")
    return f"«{oid}»"


def registry_lean(records: list[dict[str, Any]], bindings: dict[str, list[str]]) -> str:
    lines = [
        REGISTRY_BEGIN,
        "-- Generated by `verislop formalize`. Typed obligation metadata: an index, never evidence.",
        f"namespace {REGISTRY_NS}",
        "",
        "structure SourceRef where",
        "  documentRef : String",
        "  documentHash : String",
        "  startByte : Nat",
        "  endByte : Nat",
        "  origin : String",
        "  interpretation : String",
        "",
        "structure Dependency where",
        "  id : String",
        "  relation : String",
        "",
        "structure Entry where",
        "  id : String",
        "  revision : Nat",
        "  kind : String",
        "  role : String",
        "  statement : String",
        "  required : Bool",
        "  sourceRefs : List SourceRef",
        "  scope : List String",
        "  dependencies : List Dependency",
        "  acceptanceCriteria : List String",
        "  bindings : List String",
        "",
    ]
    names = []
    for r in records:
        srcs = [
            "{ documentRef := %s, documentHash := %s, startByte := %d, endByte := %d, origin := %s, interpretation := %s }"
            % (lean_string(s["document_ref"]), lean_string(s["document_hash"]), s["start_byte"], s["end_byte"],
               lean_string(s["origin"]), lean_string(s["interpretation"]))
            for s in r["source_refs"]
        ]
        deps = ["{ id := %s, relation := %s }" % (lean_string(d["id"]), lean_string(d["relation"])) for d in r["dependencies"]]
        name = _guillemet(r["id"])
        names.append(name)
        lines += [
            f"def {name} : Entry := {{",
            f"  id := {lean_string(r['id'])},",
            f"  revision := {r['revision']},",
            f"  kind := {lean_string(r['kind'])},",
            f"  role := {lean_string(r['role'])},",
            f"  statement := {lean_string(r['statement'])},",
            f"  required := {'true' if r['required'] else 'false'},",
            f"  sourceRefs := {_lean_list(srcs)},",
            f"  scope := {_lean_list([lean_string(x) for x in r['scope']])},",
            f"  dependencies := {_lean_list(deps)},",
            f"  acceptanceCriteria := {_lean_list([lean_string(x) for x in r['acceptance_criteria']])},",
            f"  bindings := {_lean_list([lean_string(x) for x in bindings.get(r['id'], [])])} }}",
            "",
        ]
    lines += [f"def entries : List Entry := {_lean_list(names)}", "", f"end {REGISTRY_NS}", REGISTRY_END, ""]
    return "\n".join(lines)


def _header_token(source: str, i: int) -> tuple[str, int, int]:
    """Read one header token, skipping whitespace and nested Lean comments."""
    n = len(source)
    while i < n:
        if source[i].isspace():
            i += 1
            continue
        if source.startswith("--", i):
            j = source.find("\n", i)
            i = n if j == -1 else j + 1
            continue
        if source.startswith("/-", i):
            depth, j = 1, i + 2
            while j < n and depth:
                if source.startswith("/-", j):
                    depth, j = depth + 1, j + 2
                elif source.startswith("-/", j):
                    depth, j = depth - 1, j + 2
                else:
                    j += 1
            if depth:
                raise ValueError("unterminated block comment in header")
            i = j
            continue
        break
    start = i
    while i < n and not source[i].isspace() and not source.startswith(("--", "/-"), i):
        i += 1
    return source[start:i], start, i


def split_header(source: str) -> tuple[int, list[str], list[str]]:
    """Find the module/import header; Lean remains the authoritative parser.

    Support Lean 4.34's `(public)? (meta)? import (all)? Name` grammar. Sections and
    private declarations are body commands and stay after the injected, scoped registry.
    """
    imports: list[str] = []
    end_of_header = 0
    try:
        word, _, end = _header_token(source, 0)
        is_module = word == "module"
        if is_module:
            end_of_header = end
        cursor = end_of_header
        while True:
            word, _, end = _header_token(source, cursor)
            if word == "prelude":
                return end_of_header, imports, ["`prelude` contracts are unsupported: the registry requires Init"]
            modified = False
            if word == "public":
                modified = True
                word, _, end = _header_token(source, end)
            if word == "meta":
                modified = True
                word, _, end = _header_token(source, end)
            if word != "import":
                break
            word, _, end = _header_token(source, end)
            if word == "all":
                modified = True
                word, _, end = _header_token(source, end)
            if modified and not is_module:
                return end_of_header, imports, ["modified imports require a `module` header"]
            if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_']*(?:\.[A-Za-z_][A-Za-z0-9_']*)*", word):
                return end_of_header, imports, ["unsupported or missing module name in import header"]
            imports.append(word)
            cursor = end_of_header = end
        return end_of_header, imports, []
    except ValueError as exc:
        return end_of_header, imports, [str(exc)]


def compose_challenge(candidate: bytes, registry: str) -> tuple[bytes, list[str], list[str]]:
    text = candidate.decode("utf-8")
    if REGISTRY_BEGIN in text:
        return candidate, [], ["candidate source already contains a VeriSlop registry block"]
    pos, imports, problems = split_header(text)
    if not problems and _header_token(text, 0)[0] == "module":
        # Keep registry names stable and available without changing the candidate's default
        # private visibility. Full values are read from the private-level kernel export.
        registry = "public section\n" + registry + "\nend\n"
    composed = text[:pos] + ("\n" if pos else "") + "\n" + registry + "\n" + text[pos:].lstrip("\n")
    return composed.encode("utf-8"), imports, problems


# ------------------------------------------------------------------------------------------
# registry decoding (bounded structural reduction of closed data)
# ------------------------------------------------------------------------------------------

class RegistryError(Exception):
    pass


def _dec_str(e: dict[str, Any]) -> str:
    if "lit" in e and "str" in e["lit"]:
        return e["lit"]["str"]
    raise RegistryError("expected a string literal")


def _dec_nat(e: dict[str, Any]) -> int:
    if "lit" in e and "nat" in e["lit"]:
        return int(e["lit"]["nat"])
    n, args = head_const(e)
    if n == "OfNat.ofNat" and len(args) == 3 and "lit" in args[1]:
        if head_const(args[2]) == ("instOfNatNat", [args[1]]):
            return int(args[1]["lit"]["nat"])
    raise RegistryError("expected a natural number literal")


def _dec_bool(e: dict[str, Any]) -> bool:
    n, args = head_const(e)
    if n in ("Bool.true", "Bool.false") and not args:
        return n == "Bool.true"
    raise RegistryError("expected a Bool constructor")


def _dec_list(e: dict[str, Any], item, decls: dict[str, Any], fuel: list[int]) -> list[Any]:
    out = []
    while True:
        fuel[0] -= 1
        if fuel[0] < 0:
            raise RegistryError("registry decoding fuel exhausted")
        n, args = head_const(e)
        if n == "List.nil" and len(args) == 1:
            return out
        if n == "List.cons" and len(args) == 3:
            out.append(item(_unfold(args[1], decls, fuel)))
            e = args[2]
            continue
        raise RegistryError("expected a closed list")


def _unfold(e: dict[str, Any], decls: dict[str, Any], fuel: list[int]) -> dict[str, Any]:
    n, args = head_const(e)
    while n and not args and n.startswith(REGISTRY_NS + ".") and decls.get(n, {}).get("kind") == "definition":
        fuel[0] -= 1
        if fuel[0] < 0:
            raise RegistryError("registry decoding fuel exhausted")
        e = decls[n]["value"]
        n, args = head_const(e)
    return e


def _mk(e: dict[str, Any], ctor: str, arity: int) -> list[dict[str, Any]]:
    n, args = head_const(e)
    if n != f"{REGISTRY_NS}.{ctor}" or len(args) != arity:
        raise RegistryError(f"expected {ctor} with {arity} fields")
    return args


def decode_registry(decls: dict[str, dict[str, Any]]) -> list[dict[str, Any]]:
    root = decls.get(f"{REGISTRY_NS}.entries")
    if root is None or root["kind"] != "definition":
        raise RegistryError("VeriSlop.Registry.entries is missing")
    fuel = [100_000]

    def src(e):
        a = _mk(e, "SourceRef.mk", 6)
        return {"document_ref": _dec_str(a[0]), "document_hash": _dec_str(a[1]), "start_byte": _dec_nat(a[2]),
                "end_byte": _dec_nat(a[3]), "origin": _dec_str(a[4]), "interpretation": _dec_str(a[5])}

    def dep(e):
        a = _mk(e, "Dependency.mk", 2)
        return {"id": _dec_str(a[0]), "relation": _dec_str(a[1])}

    def entry(e):
        a = _mk(e, "Entry.mk", 11)
        return {
            "id": _dec_str(a[0]), "revision": _dec_nat(a[1]), "kind": _dec_str(a[2]), "role": _dec_str(a[3]),
            "statement": _dec_str(a[4]), "required": _dec_bool(a[5]),
            "source_refs": _dec_list(a[6], src, decls, fuel), "scope": _dec_list(a[7], _dec_str, decls, fuel),
            "dependencies": _dec_list(a[8], dep, decls, fuel),
            "acceptance_criteria": _dec_list(a[9], _dec_str, decls, fuel),
            "bindings": _dec_list(a[10], _dec_str, decls, fuel),
        }

    return _dec_list(root["value"], entry, decls, fuel)


