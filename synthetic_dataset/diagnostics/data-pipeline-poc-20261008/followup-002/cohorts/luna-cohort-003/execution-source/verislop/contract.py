RECORD_FIELDS = ("id", "revision", "kind", "role", "statement", "required", "source_refs", "scope",
                 "dependencies", "acceptance_criteria")


def record_digest(rec: dict[str, Any]) -> str:
    return canonical.digest_json({k: rec[k] for k in RECORD_FIELDS})


def interpreted_records(draft: dict[str, Any], blocked: dict[str, list[str]]) -> list[dict[str, Any]]:
    out = []
    for category in DRAFT_CATEGORIES:
        for r in draft[category]:
            rec = {k: r[k] for k in RECORD_FIELDS}
            rec["origin"] = "interpreted"
            rec["record_digest"] = record_digest(rec)
            rec["blocked_by"] = list(blocked.get(r["id"], []))
            out.append(rec)
    return out


def derived_non_vacuity(item: dict[str, Any], by_id: dict[str, dict[str, Any]]) -> dict[str, Any]:
    """Registered formalization rule verislop.non-vacuity/0.1: derived provenance only."""
    refs = []
    scope: list[str] = []
    for aid in item["witnesses_for"]:
        a = by_id[aid]
        for src in a["source_refs"]:
            refs.append({**src, "origin": "inferred",
                         "interpretation": f"derived by registered rule verislop.non-vacuity/0.1 from assumption {aid}"})
        scope.extend(x for x in a["scope"] if x not in scope)
    rec = {
        "id": item["id"],
        "revision": 1,
        "kind": "non_vacuity",
        "role": "guarantee",
        "statement": f"Non-vacuity: {item['description']} (witnesses {', '.join(item['witnesses_for'])})",
        "required": True,
        "source_refs": refs,
        "scope": scope or ["formal contract"],
        "dependencies": [{"id": aid, "relation": "uses_definition"} for aid in item["witnesses_for"]],
        "acceptance_criteria": ["Prove the existential theorem with concrete witnesses extractable by bounded kernel head-normalisation."],
        "origin": "derived",
    }
    rec["record_digest"] = record_digest(rec)
    rec["blocked_by"] = []
    return rec


