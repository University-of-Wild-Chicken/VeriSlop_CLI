def challenge_dir(pkg) -> Path:
    return pkg.path("contract") / "challenge"


def challenge_inputs(pkg) -> dict[str, Path]:
    d = challenge_dir(pkg)
    rel = pkg.rel(d)
    files = {f"{rel}/{f}": d / f for f in CHALLENGE_FILES}
    files["claims.json"] = pkg.path("claims")
    return files


def challenge_manifest(pkg) -> dict[str, Any] | None:
    d = challenge_dir(pkg)
    if not (d / "challenge.json").is_file():
        return None
    rows = []
    for rel, path in sorted(challenge_inputs(pkg).items(), key=lambda kv: kv[0].encode("utf-8")):
        if path.is_file() and not path.is_symlink():
            data = path.read_bytes()
            rows.append({"path": rel, "sha256": canonical.digest(data), "size": len(data)})
        else:
            rows.append({"path": rel, "sha256": "missing", "size": 0})
    return {"format": fsutil.MANIFEST_FORMAT, "newline_policy": "bytes-exact", "symlinks": "rejected",
            "case_collisions": "rejected", "entries": rows}


def load_frozen(pkg) -> tuple[dict[str, Any] | None, list[Diagnostic]]:
    """Load challenge.json and verify every frozen input against its manifest."""
    d = challenge_dir(pkg)
    path = d / "challenge.json"
    if not path.is_file():
        return None, [Diagnostic("VERIFIER_NOT_RUN", "no frozen challenge; run `verislop formalize` first")]
    ch = canonical.load_file(path)
    diags: list[Diagnostic] = []
    current = challenge_manifest(pkg)
    stored = {r["path"]: r for r in ch["manifest"]["entries"]}
    for row in current["entries"]:
        if stored.get(row["path"], {}).get("sha256") != row["sha256"]:
            diags.append(Diagnostic("INPUT_MUTATION", f"frozen challenge input {row['path']} changed after freeze"))
    if fsutil.manifest_root(ch["manifest"]) != ch["contract_input_root"]:
        diags.append(Diagnostic("INPUT_MUTATION", "challenge.json root does not match its manifest"))
    return ch, diags


def frozen_json(pkg, name: str) -> Any:
    return canonical.load_file(challenge_dir(pkg) / name)
